"""Adversarial premise, semantic and schema audits, separate from scientific efficacy."""
from copy import deepcopy
import json
import numpy as np
import experiment as e
import revision as r

def certificate(data):
    md=data['metadata'];groups={}
    for row in data['dev']:
        groups.setdefault((row['u'],row['h']),[]).append(row)
    witnesses=[]
    for key,rows in groups.items():
        for a in rows:
            for b in rows:
                if a['history']==b['history']:continue
                if a['times']!=b['times'] or a['dt']!=b['dt']:continue
                gap=abs(a['o']-b['o'])
                if gap>2*md['noise_bound']:witnesses.append(dict(current_inputs=key,gap=gap,histories=[a['history'],b['history']]))
    premises=all(md[k] is True for k in ['shared_parameters','deterministic_response_assumption','measurement_stable'])
    bound=np.isfinite(md['noise_bound']) and md['noise_bound']>=0
    return dict(hard=bool(premises and bound and witnesses),witness_count=len(witnesses),witness=witnesses[0] if witnesses else None,scope='Exact recorded current inputs, shared deterministic response, stable observation and supplied absolute error bound. Measurement/determinism are conditional simulator assumptions.')

def typed_schema():
    leaf=r.obj(dict(op=dict(type='string',enum=['u','h','history','times','dt','p0','p1','p2','p3']),value=dict(type='null'),args=r.array({},maxItems=0)))
    constant=r.obj(dict(op=dict(type='string',enum=['constant']),value=dict(type='number'),args=r.array({},maxItems=0)))
    unary=r.obj(dict(op=dict(type='string',enum=r.UNARY),value=dict(type='null'),args=r.array({'$ref':'#/$defs/node'},minItems=1,maxItems=1)))
    binary=r.obj(dict(op=dict(type='string',enum=r.BINARY),value=dict(type='null'),args=r.array({'$ref':'#/$defs/node'},minItems=2,maxItems=2)))
    return {'$defs':{'node':{'anyOf':[leaf,constant,unary,binary]}},'$ref':'#/$defs/node'}

def main():
    import jsonschema
    evidence=e.read(e.ROOT/'visible/evidence.json');checks={};cases={}
    cases['original_exact_match']=certificate(evidence);checks['exact_case_certified']=cases['original_exact_match']['hard']
    approximate=deepcopy(evidence)
    for row in approximate['dev']:
        if row['history'][0]>0:row['u']+=1e-6
    cases['approximate_match']=certificate(approximate);checks['near_match_does_not_exclude_arbitrary_nonlinearity']=not cases['approximate_match']['hard']
    old=e.verify_constraints(e.read(e.ROOT/'CONSTRAINT_PROPOSALS.json'),approximate)
    checks['original_validator_drift_exposed']=bool(old['certified'])
    for key in ['shared_parameters','deterministic_response_assumption','measurement_stable']:
        changed=deepcopy(evidence);changed['metadata'][key]=False;cases[key+'_false']=certificate(changed);checks[key+'_withdraws']=not cases[key+'_false']['hard']
    wide=deepcopy(evidence);wide['metadata']['noise_bound']=2.;cases['wide_noise_bound']=certificate(wide);checks['no_conflict_when_noise_explains_gap']=not cases['wide_noise_bound']['hard']
    # Both coordinate representations produce the same raw observables and are retained.
    rows=evidence['dev'];params=[2.2,.7,.3,.8]
    a=dict(quantities=[dict(name='Y',expression='sum(history*exp(times/p[0]))*dt*exp(-h/p[0])')],expression='p[1]*u+p[2]*u**3+p[3]*Y')
    b=dict(quantities=[dict(name='Q',expression='2*sum(history*exp(times/p[0]))*dt*exp(-h/p[0])')],expression='p[1]*u+p[2]*u**3+p[3]*Q/2')
    pred_a=e.predictor(a)(rows,params);pred_b=e.predictor(b)(rows,params)
    checks['equivalent_state_coordinates_preserve_observables']=bool(np.max(np.abs(pred_a-pred_b))<1e-12)
    checks['feasible_model_meets_recorded_noise_bound']=bool(np.max(np.abs(pred_a-[x['o'] for x in rows]))<=.015)
    checks['feasible_model_not_current_only']=bool(np.ptp(pred_a[:12])>.03)
    # This is an evaluator fixture, never generated by or exposed to researchers.
    schema=typed_schema();e.write(e.ROOT/'repairs/TYPED_NODE_SCHEMA.json',schema)
    raw=e.read(e.ROOT/'revision_R1/raw_candidates.json')['candidates'];validation=[]
    for c in raw:
        try:jsonschema.validate(c['tree'],schema);valid=True
        except jsonschema.ValidationError:valid=False
        validation.append(dict(id=c['id'],valid=valid))
    checks['typed_schema_rejects_malformed_R1']=not validation[0]['valid']
    checks['typed_schema_preserves_valid_R2_R3']=all(x['valid'] for x in validation[1:])
    p4=dict(op='p4',value=None,args=[])
    try:jsonschema.validate(p4,schema);checks['undeclared_parameter_leaf_rejected']=False
    except jsonschema.ValidationError:checks['undeclared_parameter_leaf_rejected']=True
    e.write(e.ROOT/'IMPLEMENTATION_CHECKS.json',dict(time=e.now(),source_sha256=e.sha(__file__),checks=checks,passed=all(checks.values()),premise_cases=cases,schema_cases=validation,important_correction='Original verifier trusted a matching-description string. On perturbed u data that verifier incorrectly retained a hard constraint. The independent v2 verifier groups actual u,h values and removes hard status when no exact collision remains. Original exact-match scientific inference remains valid; frozen source unchanged.',scope='Controlled soundness and equivalence audit; no new research model call and no method efficacy result',typed_schema_status='Locally verified fix for a future run; not used to regenerate this run\'s candidates'))
    assert all(checks.values())
    print(json.dumps(dict(checks=checks,passed=all(checks.values())),ensure_ascii=False))

if __name__=='__main__':main()
